/**
 * Gemini가 격식체(~습니다/~ㅂ니다)로 끝맺는 경우를 요체로 자동 변환하는 안전장치.
 */
export function koreanizeYoche(s: string): string {
  if (typeof s !== "string") return s;
  const replacements: [RegExp, string][] = [
    [/했습니다([.!?…]?)/g, "했어요$1"],
    [/입니다([.!?…]?)/g, "이에요$1"],
    [/합니다([.!?…]?)/g, "해요$1"],
    [/됩니다([.!?…]?)/g, "돼요$1"],
    [/있습니다([.!?…]?)/g, "있어요$1"],
    [/없습니다([.!?…]?)/g, "없어요$1"],
    [/같습니다([.!?…]?)/g, "같아요$1"],
    [/그렇습니다([.!?…]?)/g, "그래요$1"],
    [/아닙니다([.!?…]?)/g, "아니에요$1"],
    [/입니까([.!?…]?)/g, "예요$1"],
    [/습니까([.!?…]?)/g, "어요$1"],
    [/(\S)습니다([.!?…\s]|$)/g, "$1어요$2"],
    [/(\S)ㅂ니다([.!?…\s]|$)/g, "$1요$2"],
  ];
  let out = s;
  for (const [re, rep] of replacements) out = out.replace(re, rep);
  return out;
}
